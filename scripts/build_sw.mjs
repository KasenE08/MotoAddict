// Writes sw.js: precaches every file the game needs so it plays fully offline.
// The cache name includes a hash of all files, so any change ships a fresh cache.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const roots = ['index.html', 'manifest.webmanifest', 'src', 'assets/fonts', 'assets/sfx', 'assets/icons'];
const files = [];
const walk = (p) => { const st = fs.statSync(p); if (st.isDirectory()) fs.readdirSync(p).sort().forEach((f) => walk(path.join(p, f))); else if (!p.endsWith('.md')) files.push(p); };
roots.forEach(walk);
const hash = crypto.createHash('sha1');
for (const f of files) hash.update(f).update(fs.readFileSync(f));
const version = hash.digest('hex').slice(0, 10);
const list = ['./', ...files.map((f) => `./${f}`)];
fs.writeFileSync('sw.js', `// Generated by scripts/build_sw.mjs — do not edit by hand.
const CACHE = 'motoaddict-${version}';
const FILES = ${JSON.stringify(list, null, 0)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('motoaddict-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).catch(() => (e.request.mode === 'navigate' ? caches.match('./') : undefined))),
  );
});
`);
console.log(`sw.js: ${list.length} files, cache ${version}`);
